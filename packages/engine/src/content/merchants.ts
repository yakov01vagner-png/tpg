/**
 * Купцы — данные, а не код (этап 49).
 *
 * До 0.6 рынок был таблицей: место, товар, цена. Торговали с местом, а не с
 * человеком, и место ничего не помнило. Здесь лежит то, что у купцов
 * авторского: ряды, нравы, имена и слова. Кто сегодня стоит за прилавком,
 * решает мир (`merchant.ts`): купцы выводятся из места и времени, а в
 * состоянии хранится только память о встречах.
 */

/** Ряд: где чем торгуют. Рынок — не куча, а ряды, и это видно с порога. */
export interface RowDef {
  readonly id: string
  readonly label: string
  /** Чем торгуют в этом ряду. */
  readonly goods: readonly GoodId[]
  /** Сколько народу должно жить в месте, чтобы ряд завёлся. */
  readonly minPopulation: number
}

