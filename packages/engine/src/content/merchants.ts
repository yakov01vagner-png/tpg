/**
 * Нрав купца: как он держит цену и что помнит.
 *
 * `hold` — насколько трудно его сбить (0 уступит сразу, 1 не уступит вовсе),
 * `markup` — его собственная надбавка к цене места, `memory` — во сколько раз
 * крепче обычного он помнит хорошее и дурное.
 */
export type MerchantTemper = 'stingy' | 'generous' | 'proud' | 'shrewd' | 'jovial' | 'sour'

export interface MerchantTemperDef {
  readonly id: MerchantTemper
  readonly label: string
  readonly hold: number
  readonly markup: number
  readonly memory: number
  /** Что скажет, когда сбивают цену и он уступает. */
  readonly yields: readonly string[]
  /** Что скажет, когда не уступает. */
  readonly holds: readonly string[]
  /** Что скажет, когда перегнул палку и его обидели. */
  readonly offended: readonly string[]
  /** Чем встретит своего. */
  readonly greets: readonly string[]
}

